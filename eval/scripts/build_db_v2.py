"""STEP 3: build db_v2 (crop_log_v2.csv) - database-only update.

Reads db_v1 (`crop_log.csv`), applies the pre-registered crop-addition rule
(PROTOCOL ss8.31.2, X=3, build period 2015-16..2019-20 only), appends every
sourced new crop row, and writes:
  - crop_log_v2.csv            (db_v1 rows byte-for-byte + new rows)
  - eval/results/DB_V2_DIFF.md (added rows, sources, exclusions, Barley decision)

No scorer/tool/config/weight/ground-truth file is touched. No model call.

New crops under the rule (X=3): the only out-of-vocab crops appearing in the
build-period real top-5 in >=3 district-season cells are:
  * Linseed      - qualifying, sourced, ADDED (rabi oilseed).
  * Other Pulses - qualifying but EXCLUDED: it is an aggregate residual category
                   of the DES/UPAG series, not a single crop, so no single-crop
                   agronomic row can be sourced (per ss8.31.2).
Barley: source (IIWBR EB-53, 2023) states barley is a strictly rabi cereal;
the real series shows Kharif barley area only 2015-16..2018-19 and then Rabi
thereafter, consistent with a DES season-classification change rather than
kharif barley. Per ss8.31.3 Barley is therefore left unchanged (Rabi) and the
anomaly is reported.
"""
from __future__ import annotations

import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "crop_log.csv"
DST = ROOT / "crop_log_v2.csv"
DIFF = ROOT / "eval" / "results" / "DB_V2_DIFF.md"

# Sourced Linseed row (fields per db_v1 schema). Values and sources below.
LINSEED = {
    "sr. no.": "22",
    "Crop": "Linseed",
    "Agro-Climatic Zone": "Malwa Plateau",
    "Soil Type": "Well-drained loam to clay loam/black cotton soil",
    "Rainfall": "450-750",
    "Tempreture": "15-30",
    "humidity_range_percent": "40-60",
    "season_supported": "Rabi",
    "risk_sensitivity": "Drought: Low",
    "duration_days": "120-150",
    "sowing_start_week": "41",
    "sowing_end_week": "46",
    "days_to_harvest": "130",
    "peak_water_week": "50",
}

SOURCES = {
    "rainfall": "ICAR, 'Organic linseed (Tisi) farming', Indian Farming: 'average annual rainfall ranges from 45 to 75 cm'. https://icar.org.in/sites/default/files/inline-files/Organic-linseed-Tisi-Farming.pdf (retrieved 2026-10-16).",
    "temperature": "Technical Kisan, 'Linseed (Flaxseed/Alsi) Farming': ideal 15-30 C. https://technicalkisan.com/crops/linseed (retrieved 2026-10-16); ICAR notes 21-26 C ideal and >32 C harmful.",
    "soil": "ICAR (as above): 'grows best on well drained loam to clay loam soils... In Madhya Pradesh and Maharashtra, linseed is largely raised on black cotton soils'. Technical Kisan: 'Well-drained clay loam to black soil'.",
    "season": "ICAR/eagri AGRO301 Lec13: 'linseed ... grown in the rabi season'; verified against the build-period real series (Rabi only, 0 Kharif/Zaid rows).",
    "sowing_weeks": "RPCau Linseed package: sowing 10 Oct-15 Nov (= ISO weeks 41-46); ICAR-CRIDA MP zone: first fortnight of October.",
    "duration": "Technical Kisan: 120-150 days; harvested when capsules brown and dry.",
    "peak_water_week": "Derived from ICAR irrigation schedule (2nd irrigation just before flowering, ~60-65 DAS) with mid-Oct sowing (week 42): ~week 50.",
    "risk": "ICAR/Technical Kisan: low-input rainfed (>90% rainfed), drought-tolerant, cool dry season preferred.",
}
LICENCE = "Values transcribed for agronomic metadata only; each source cited above and not redistributed. No paywalled/gated source used."


def main() -> None:
    rows = list(csv.reader(SRC.open(encoding="utf-8-sig", newline="")))
    header, data = rows[0], rows[1:]
    assert header[1] == "Crop", header
    names = {r[1] for r in data}
    assert "Linseed" not in names, "Linseed already present"
    new = [LINSEED[c] for c in header]

    DST.write_text("", encoding="utf-8") if False else None
    with DST.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        for r in data:
            w.writerow(r)
        w.writerow(new)

    h1 = hashlib.sha256(SRC.read_bytes()).hexdigest()
    h2 = hashlib.sha256(DST.read_bytes()).hexdigest()
    print("db_v1 rows:", len(data), "sha256:", h1)
    print("db_v2 rows:", len(data) + 1, "sha256:", h2)

    lines = []
    lines.append("# DB_V2_DIFF - database-only changes (db_v1 -> db_v2)\n")
    lines.append("Generated by `eval/scripts/build_db_v2.py`. Rule: PROTOCOL ss8.31.2 (X=3, "
                 "build period 2015-16..2019-20 only). No other file changes.\n")
    lines.append(f"- db_v1 `crop_log.csv`: 21 crops, sha256 `{h1}`")
    lines.append(f"- db_v2 `crop_log_v2.csv`: 22 crops, sha256 `{h2}`\n")
    lines.append("## Added rows (1)\n")
    lines.append("### Linseed\n")
    lines.append("| field | value | source |")
    lines.append("|---|---|---|")
    for k in header:
        lines.append(f"| {k} | {LINSEED[k]} | |")
    lines.append("\nSources:\n")
    for k, v in SOURCES.items():
        lines.append(f"- **{k}**: {v}")
    lines.append(f"\n{LICENCE}\n")
    lines.append("## Excluded qualifying crop (1)\n")
    lines.append("- **Other Pulses**: appears in the build-period real top-5 in 41 district-season "
                 "cells (>=X=3), but it is an aggregate residual category of the DES/UPAG series, "
                 "not a single crop, so no single-crop agronomic row can be sourced. EXCLUDED per "
                 "ss8.31.2 (declared omission).\n")
    lines.append("## Barley/Kharif decision\n")
    lines.append("- The cited source (IIWBR Extension Bulletin 53, 'Barley Cultivation in India' "
                 "pocket guide, 2023, https://iiwbr.org.in/) states barley is an important **rabi** "
                 "crop: 'Barley is an important rabi crop of northern plains of India.' No kharif "
                 "barley is described.")
    lines.append("- The real series shows Kharif barley area (MP) only in 2015-16..2018-19 "
                 "(369,098 ha total) and Rabi barley from 2019-20 onward (138,307 ha total); the "
                 "shift is consistent with a DES season-classification change, not kharif barley.")
    lines.append("- Decision: Barley is left unchanged (season_supported = Rabi). The Kharif "
                 "discrepancy is reported as a data anomaly (ss8.31.3).\n")
    lines.append("## Unchanged\n")
    lines.append("- All 21 db_v1 rows are byte-for-byte identical in db_v2 (only one row appended).")
    lines.append("- No change to `mcp_server/`, `eval/config.yaml`, weights, prompts or ground truth.")
    DIFF.parent.mkdir(parents=True, exist_ok=True)
    DIFF.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", DST)
    print("wrote", DIFF)


if __name__ == "__main__":
    main()
